#!/usr/bin/env python3
"""Measured source distribution by language and role (stdlib only). Measured, never targeted (plan §5.8, ADR-088).

  python3 tools/loc_report.py                      # print the table
  python3 tools/loc_report.py --write docs/CODE_DISTRIBUTION.md
Counts physical lines. Skips reference/, any imported/ directory, build output, .git, docs/ and the SDK mirror inside
runtime/python (a generated copy of sdk-python/autohost, see tools/sync_sdk.py).
"""
import argparse, collections, pathlib, sys

SKIP = {".git", "build", ".gradle", "reference", "imported", "node_modules", "__pycache__", "docs"}
LANG = {".kt": "Kotlin", ".kts": "Gradle (Kotlin DSL)", ".py": "Python", ".java": "Java", ".c": "C/C++", ".cc": "C/C++", ".cpp": "C/C++",
        ".h": "C/C++", ".hpp": "C/C++", ".js": "JavaScript", ".json": "JSON", ".xml": "XML", ".aidl": "AIDL", ".yml": "YAML", ".yaml": "YAML"}


def role(rel):
    p = rel.as_posix()
    ext = rel.suffix
    if p.startswith("runtime/python/src/main/python/"):
        return None  # generated mirror of sdk-python/autohost
    if ext == ".py":
        if p.startswith("sdk-python/autohost/"): return "Python embedded in the app (SDK)"
        if p.startswith("sdk-python/tests/") or p.startswith("tests/"): return "Python tests"
        if p.startswith("samples/"): return "Python sample tasks (user-style scripts)"
        return "Python PC tooling (simulator, CLI, MCP, generators)"
    if ext in (".kt", ".java"):
        if "/src/test/" in p or "/src/androidTest/" in p: return "Kotlin tests"
        if p.startswith("testing/"): return "Kotlin test fixture app"
        return "Kotlin shipped in the app"
    if ext in (".json",):
        return "Schemas, vectors and specs" if not p.startswith("samples/") else "Sample manifests"
    return "Build, resources and glue"


def measure(root):
    rows = collections.defaultdict(lambda: [0, 0])
    for f in sorted(root.rglob("*")):
        if not f.is_file() or f.suffix not in LANG:
            continue
        rel = f.relative_to(root)
        if any(part in SKIP for part in rel.parts):
            continue
        r = role(rel)
        if r is None:
            continue
        try:
            n = sum(1 for _ in f.open("rb"))
        except OSError:
            continue
        key = (LANG[f.suffix], r)
        rows[key][0] += 1
        rows[key][1] += n
    return rows


def render(rows):
    out = ["| Language | Role | Files | Lines |", "|---|---|---|---|"]
    for (lang, r), (nf, nl) in sorted(rows.items(), key=lambda kv: (-kv[1][1])):
        out.append(f"| {lang} | {r} | {nf} | {nl} |")
    kt = sum(v[1] for (l, r), v in rows.items() if r == "Kotlin shipped in the app")
    py = sum(v[1] for (l, r), v in rows.items() if r == "Python embedded in the app (SDK)")
    cc = sum(v[1] for (l, r), v in rows.items() if l == "C/C++" and "test" not in r.lower())
    tot = kt + py + cc
    out += ["", f"Source that ships in the app: Kotlin {kt} lines, Python (the embedded SDK) {py} lines, C/C++ {cc} lines"
            + (f" — Python is {100 * py / tot:.1f} % of it." if tot else "."),
            "All other Python runs on the PC or in tests. This is a measurement for tracking (X-07), not a target."]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--write")
    a = ap.parse_args(argv)
    table = render(measure(pathlib.Path(a.root).resolve()))
    if a.write:
        pathlib.Path(a.write).write_text("# CODE_DISTRIBUTION — measured, generated by `python3 tools/loc_report.py --write docs/CODE_DISTRIBUTION.md`\n"
                                         "Do not hand-edit. Measured per milestone (X-07); no ratio is targeted (plan §5.8).\n\n" + table + "\n", encoding="utf-8")
    print(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
