#!/usr/bin/env python3
"""gen_artifacts (P5-15): generate the derived artifacts from capability-specs.w1.json.

Outputs (single source of truth, plan §5.5 — never hand-edit):
  docs/CAPABILITIES.md                      — the human catalog
  sdk-python/autohost/_capabilities_gen.py  — the machine catalog the SDK `capabilities()` uses
  core/broker/src/main/resources/autohost/capability-specs-w1.json — the broker's bundled copy
    (P8: synced from schemas/ byte-for-byte so PermissionIndex and the docs can never diverge)

--check regenerates into memory and fails (exit 1) when a committed file drifts, which is exactly
what tests/test_gen_artifacts.py asserts.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "schemas" / "capability-specs.w1.json"
DOC_OUT = ROOT / "docs" / "CAPABILITIES.md"
PY_OUT = ROOT / "sdk-python" / "autohost" / "_capabilities_gen.py"
BROKER_RESOURCE = ROOT / "core" / "broker" / "src" / "main" / "resources" / "autohost" / "capability-specs-w1.json"


def load() -> dict:
    with SPEC.open(encoding="utf-8") as fh:
        return json.load(fh)


def capabilities_doc(spec: dict) -> str:
    lines = [
        "<!-- GENERATED by tools/gen_artifacts.py — edit schemas/capability-specs.w1.json instead -->",
        "",
        "# Capabilities (wave 1 + host)",
        "",
        "| id | tier(s) | minSdk | summary | methods | permissions |",
        "|---|---|---|---|---|---|",
    ]
    for cap in spec.get("capabilities", []):
        tiers = ", ".join(cap.get("tiers", []))
        methods = ", ".join(f"`{m.get('name', '?')}`" for m in cap.get("methods", []))
        perms = ", ".join(p.get("id", "?") for p in cap.get("permissions", []))
        summary = cap.get("summary", "").replace("|", "\\|")
        lines.append(
            f"| `{cap.get('id', '?')}` | {tiers} | {cap.get('minSdk', 26)} | {summary} | {methods} | {perms} |"
        )
    lines += ["", "## Host events", ""]
    for event in spec.get("hostEvents", []):
        name = event.get("name", "?") if isinstance(event, dict) else str(event)
        desc = event.get("description", "") if isinstance(event, dict) else ""
        lines.append(f"- `{name}` — {desc}")
    lines.append("")
    return "\n".join(lines)


def capabilities_py(spec: dict) -> str:
    payload = json.dumps(spec.get("capabilities", []), indent=2, sort_keys=True)
    return (
        '"""GENERATED by tools/gen_artifacts.py — the machine-readable capability catalog (plan §5.5).\n\n'
        'Do not edit; change schemas/capability-specs.w1.json and regenerate.\n"""\n\n'
        "CATALOG = " + payload + "\n"
    )


def generate() -> dict[str, str]:
    spec = load()
    return {
        "doc": capabilities_doc(spec),
        "py": capabilities_py(spec),
        # The broker resource is a byte copy of the schema file (P8-13/P8-01 permission indexing).
        "resource": SPEC.read_text(encoding="utf-8"),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when committed outputs drift")
    args = parser.parse_args(argv)

    out = generate()
    if args.check:
        problems = []
        if DOC_OUT.read_text(encoding="utf-8") != out["doc"]:
            problems.append(f"{DOC_OUT.relative_to(ROOT)} drifted; run tools/gen_artifacts.py")
        if PY_OUT.read_text(encoding="utf-8") != out["py"]:
            problems.append(f"{PY_OUT.relative_to(ROOT)} drifted; run tools/gen_artifacts.py")
        if BROKER_RESOURCE.read_text(encoding="utf-8") != out["resource"]:
            problems.append(f"{BROKER_RESOURCE.relative_to(ROOT)} drifted; run tools/gen_artifacts.py")
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            return 1
        print("generated artifacts in sync")
        return 0
    DOC_OUT.write_text(out["doc"], encoding="utf-8")
    PY_OUT.write_text(out["py"], encoding="utf-8")
    BROKER_RESOURCE.write_text(out["resource"], encoding="utf-8")
    print(
        f"wrote {DOC_OUT.relative_to(ROOT)}, {PY_OUT.relative_to(ROOT)} and "
        f"{BROKER_RESOURCE.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
