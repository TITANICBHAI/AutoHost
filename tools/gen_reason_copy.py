#!/usr/bin/env python3
"""Writes app/src/main/kotlin/app/autohost/ui2/ReasonCopy.kt from schemas/errors.json.

schemas/errors.json is the source of the words a person reads when a run stops (docs/CONVENTIONS.md: failure text comes
from the catalog, never from an exception message). The Kotlin file is a copy of it so the app needs no file reading.
Only codes whose text has no {placeholder} are copied: a text that needs a package name or a number is never shown
without it, and a person never sees a package name.

    python3 tools/gen_reason_copy.py            # rewrite the Kotlin file
    python3 tools/gen_reason_copy.py --check    # exit 1 if the file is out of date

ReasonCopyTest compares the generated table with the catalog on every CI run, so a change to either side fails there.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "schemas" / "errors.json"
TARGET = ROOT / "app" / "src" / "main" / "kotlin" / "app" / "autohost" / "ui2" / "ReasonCopy.kt"


def kotlin_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def render() -> str:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    plain = [
        entry
        for entry in catalog["reasonCodes"]
        if not entry.get("params") and "{" not in entry["userMessage"]
    ]
    rows = [(entry["code"], entry["userMessage"]) for entry in plain]
    # the button words the catalog gives each fix action; a reason whose fix is NONE or has no words gets no button
    labels = {fix["id"]: fix.get("label", "") for fix in catalog.get("fixActions", [])}
    fixes = [
        (entry["code"], entry["fixAction"], labels[entry["fixAction"]])
        for entry in plain
        if entry.get("fixAction") and entry["fixAction"] != "NONE" and labels.get(entry["fixAction"])
    ]
    lines = [
        "// GENERATED by tools/gen_reason_copy.py from schemas/errors.json. Do not edit by hand:",
        "// change the catalog, run the script, commit both. ReasonCopyTest fails when they differ.",
        "package app.autohost.ui2",
        "",
        "/**",
        " * The plain-language text for the reason a run stopped, copied from the error catalog",
        " * (`schemas/errors.json`, `reasonCodes`), and the button the catalog attaches to it (`fixActions`). Only reasons",
        " * that need no value (a package, a number) are here.",
        " */",
        "object ReasonCopy {",
        "    /** The catalog's text for [reason], or null when the code is unknown or its text needs a value. */",
        "    fun text(reason: String?): String? = if (reason == null) null else TABLE[reason]",
        "",
        "    /** Every code in the table, for the test that compares it with the catalog. */",
        "    val table: Map<String, String> get() = TABLE",
        "",
        "    private val TABLE: Map<String, String> = mapOf(",
    ]
    for code, text in rows:
        lines.append("        %s to %s," % (kotlin_string(code), kotlin_string(text)))
    lines += [
        "    )",
        "",
        "    /** The button the catalog attaches to [reason] (the action it names and the words on it), or null when it names none. */",
        "    fun fix(reason: String?): ReasonFix? = if (reason == null) null else FIX_TABLE[reason]",
        "",
        "    /** Every reason that has a button, for the test that compares it with the catalog. */",
        "    val fixTable: Map<String, ReasonFix> get() = FIX_TABLE",
        "",
        "    private val FIX_TABLE: Map<String, ReasonFix> = mapOf(",
    ]
    for code, action, label in fixes:
        lines.append("        %s to ReasonFix(%s, %s)," % (kotlin_string(code), kotlin_string(action), kotlin_string(label)))
    lines += [
        "    )",
        "}",
        "",
        "/** A button the catalog names for a stop: the id of what the app does, and the words on the button. */",
        "data class ReasonFix(val action: String, val label: String)",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("ReasonCopy.kt is out of date: run python3 tools/gen_reason_copy.py")
            return 1
        print("ReasonCopy.kt is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s (%d codes)" % (TARGET.relative_to(ROOT), text.count(" to \"")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
