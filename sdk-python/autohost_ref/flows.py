def _x_wait_until(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    body = step["body"]
    key = "visible" if "visible" in body else "notVisible"
    wire = _resolve_selector_labels(
        selector_from_flow(body[key], f"{label}: {key}"), scope)
    out = _call(ex, "device.ui", "wait_for",
                {"selector": wire, "timeout_ms": _timeout_ms(step)}, label, selector=wire)
    appeared = out.get("node") is not None
    if (key == "visible") == appeared:
        return
    message = "element did not appear in time" if key == "visible" else "element is still visible"
    raise StepFailure("TIMEOUT", message, retryable=True, selector=wire, label=label)


