"""Declarative flows: the reference interpreter of plan §7.9 (Phase 6).

The Kotlin interpreter (:runtime:flow `FlowInterpreter`) must produce identical results; both are
held to the shared vectors in testing/golden/flow_vectors.json (generated by
tools/gen_flow_vectors.py). Pure logic only — no I/O, no clock reads; the host supplies an `Exec`
callback surface (broker, emit, check, sleep, clock, api_level, subflows, viewport) so tests drive
time and outcomes (fake-clock on the Kotlin side).

Flow document (JSON; YAML is parsed to this shape before the interpreter sees it) — the
structural contract is schemas/flow.schema.json:

    {
      "schema": 1,
      "name": "Press button",
      "tags": ["demo"],
      "env": {"greeting": "hi"},          # flow-level variables
      "onFlowStart": [ ...steps... ],     # hooks
      "onFlowComplete": [ ...steps... ],
      "steps": [ ...steps... ]
    }

A step is an object with EXACTLY one command key whose value is the command body. Common
modifiers live inside the body: optional, label, timeout, when — and on tap-type commands also
waitToSettle / retryTapIfNoChange. `timeout` is SECONDS everywhere in the flow format (the
sample flow's `timeout: 20` reads as twenty seconds); it is converted to milliseconds for
broker calls, defaulting to 10 s.

Semantics the vectors pin down:
- variables: ${config.x.y}, ${profile.x}, ${env.X}, ${run.attempt} resolve against the scope
  (bare names try env, then config, then profile). A placeholder that resolves nowhere stays
  literal — fail closed, exactly like scope templating on the host. ${secret.NAME} resolves
  ONLY in action positions (inputText.text and setClipboard.text, both with secret: true); a
  missing secret is a typed NOT_FOUND failure; secret values are redacted in emitted events.
- a whole-string placeholder keeps the value's type ("${config.n}" with n=5 becomes the number
  5); inside a longer string, values interpolate (booleans as true/false, null as empty).
- when: {visible, notVisible, true, minApi} — every present key must hold (AND). Skipped steps
  do not consume the run's step counter.
- optional: a typed failure in an optional step is recorded (evidence event, then a warn log)
  and swallowed. Cancellation and unanswered prompts are never swallowed.
- retry: {times, steps, backoff_ms?} — `times` is the number of RETRIES after the first attempt
  (total attempts = times + 1, matching the SDK's flow.retry convention). Only retryable
  failures (broker TIMEOUT / STALE_NODE / ... class) retry; the backoff is fixed.
- repeat: {times | while, steps} — times >= 1; `while` is re-evaluated before every iteration
  and capped at 10000 iterations (fail closed).
- runFlow: {file, env?} — the subflow document is looked up in Exec.subflows; the child gets a
  COPY of the current env overlaid with the flow's own env and the runFlow `env` (child
  mutations stay in the child); result and next_run are global to the run; nesting is capped
  at 8. The child's hooks run with the child's steps.
- hooks: onFlowStart runs before the body (a non-optional hook failure fails the run before any
  body step executes); onFlowComplete runs after the body on success only; a hook failure flips
  the outcome to FAILED.
- every typed failure emits an evidence event {step, command, code, retryable, message,
  selector} before the step's fate (swallow or fail) is applied. The host attaches the compact
  dump and foreground package when persisting evidence — the interpreter does not make extra
  broker calls for it.
- failure codes are broker error codes only (schemas/errors.json). A click whose verification
  came back false is TIMEOUT (retryable); assertion failures are NOT_FOUND (terminal); wait
  timeouts are TIMEOUT (retryable).
- ask: an unanswered prompt (confirmed != true / answer == null) ends the run as WAITING_USER
  (reason NEEDS_INPUT) — a flow outcome, not a step failure.
- outcome: {"status": "SUCCEEDED|FAILED|CANCELLED|WAITING_USER", "reason"?, "message"?,
  "result": {"code", "data"}, "next_run"?} — the host emits it as the finished event. The
  interpreter emits events without `ts`; the host stamps timestamps when forwarding.
- expression language (when.true, repeat.while): literals (numbers, 's', "s", true, false),
  identifiers (bare, or config. / profile. / env. / run. dotted), ! && ||, comparisons
  (== != < <= > >=), + (numbers add, strings concatenate, mixing is an error), - on numbers,
  parentheses. Ordering comparisons need both operands to be numbers or both strings; equality
  across different types is false (booleans are not numbers). when.true / repeat.while must
  yield a boolean; secrets are refused in expressions.
- selectors (flow form -> broker wire form): text/id/desc/class/package accept a string, a list
  of strings, or {value, mode}; the default mode is eq (precise by default), `mode` overrides.
  Boolean keys fold into one state term; below/above/leftOf/rightOf/childOf/containsChild and
  containsDescendants become relation terms; `index` folds every other criterion into a single
  index-relation term (the n-th match of the rest, document order — mirrors SelectorEngine).
- commands map onto wave-1 broker methods (device.app, device.ui, device.screenshot.capture,
  device.ime.clipboard_set, notify.post.post, ui.prompt.ask). `scroll` synthesises a centre
  swipe from Exec.viewport (default 1080x2400, 300 ms).
"""
