class FlowError(ValueError):
    """The flow document is invalid (structure or shape). Raised by parse_flow only."""


class BrokerError(Exception):
    """Typed broker failure raised by the host's broker adapter. `code` is a broker error code."""

    def __init__(self, code: str, message: str = "", *, retryable: bool = False) -> None:
        super().__init__(message or code)
        self.code = code
        self.message = message or code
        self.retryable = bool(retryable)


class StepFailure(Exception):
    """A typed command failure inside the flow. `code` is a broker error code."""

    def __init__(self, code: str, message: str = "", *, retryable: bool = False,
                 selector: dict | None = None, label: str | None = None) -> None:
        super().__init__(message or code)
        self.code = code
        self.message = message or code
        self.retryable = bool(retryable)
        self.selector = selector
        self.label = label


class Cancelled(Exception):
    """Raised by Exec.check() when the run was cancelled."""


class WaitUser(Exception):
    """Raised by `ask` when nobody answers: the run outcome becomes WAITING_USER."""


class _SecretMissing(Exception):
    def __init__(self, name: str) -> None:
        super().__init__(name)
        self.name = name


class ExprError(Exception):
    pass


def _die(msg: str) -> None:
    raise FlowError(f"flow invalid: {msg}")


# ---------------------------------------------------------------------------
# document layer: parse + normalise (fail closed, precise messages)
# ---------------------------------------------------------------------------

def parse_flow(doc: Any) -> dict:
    """Validates and normalises a flow document; raises FlowError with a precise message."""
    if not isinstance(doc, dict):
        _die("document must be an object")
    unknown = set(doc) - {"schema", "name", "tags", "env", "onFlowStart", "onFlowComplete", "steps"}
    if unknown:
        _die(f"unknown top-level key(s) {sorted(unknown)}")
    if doc.get("schema") != 1 or isinstance(doc.get("schema"), bool):
        _die("schema must be the number 1")
    out: dict[str, Any] = {"schema": 1}
    name = doc.get("name")
    if name is not None and (not isinstance(name, str) or not name.strip()):
        _die("name must be a non-empty string")
    out["name"] = name
    if "tags" in doc and doc["tags"] is not None:
        tags = doc["tags"]
        if not isinstance(tags, list) or not all(isinstance(t, str) and t for t in tags):
            _die("tags must be a list of non-empty strings")
        out["tags"] = list(tags)
    env = doc.get("env") or {}
    _check_env_map(env, "env")
    out["env"] = dict(env)
    for hook in ("onFlowStart", "onFlowComplete"):
        if doc.get(hook) is not None:
            out[hook] = _parse_steps(doc[hook], hook)
    steps = doc.get("steps")
    if not isinstance(steps, list) or not steps:
        _die("steps must be a non-empty list")
    out["steps"] = _parse_steps(steps, "steps")
    return out


def _check_env_map(env: Any, where: str) -> None:
    if not isinstance(env, dict):
        _die(f"{where} must be an object")
    for key, value in env.items():
        if not isinstance(key, str) or not key:
            _die(f"{where} keys must be non-empty strings")
        if isinstance(value, bool) or not isinstance(value, (str, int, float)):
            _die(f"{where}.{key} must be a string, number or boolean")


def _parse_steps(raw: Any, where: str) -> list[dict]:
    if not isinstance(raw, list) or not raw:
        _die(f"{where} must be a non-empty list")
    return [_parse_step(item, f"{where}[{i}]") for i, item in enumerate(raw)]


def _parse_step(raw: Any, where: str) -> dict:
    if not isinstance(raw, dict):
        _die(f"{where}: step must be an object")
    if len(raw) != 1:
        _die(f"{where}: a step must have exactly one command key, got {sorted(raw)}")
    (command, body), = raw.items()
    if command not in COMMANDS:
        _die(f"{where}: unknown command {command!r}")
    if not isinstance(body, dict):
        _die(f"{where}: {command} body must be an object")

    step: dict[str, Any] = {"command": command, "body": body}
    optional = body.get("optional", False)
    if not isinstance(optional, bool):
        _die(f"{where}: optional must be a boolean")
    step["optional"] = optional
    label = body.get("label")
    if label is not None and (not isinstance(label, str) or not label):
        _die(f"{where}: label must be a non-empty string")
    step["label"] = label
    if "timeout" in body and body["timeout"] is not None:
        timeout = body["timeout"]
        if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or timeout < 0:
            _die(f"{where}: timeout must be a non-negative number of seconds")
        step["timeout_s"] = float(timeout)
    if body.get("when") is not None:
        step["when"] = _parse_when(body["when"], f"{where}: {command}")

    validator = _VALIDATORS[command]
    validator(body, step, where)
    return step


def _parse_when(when: Any, where: str) -> dict:
    if not isinstance(when, dict) or not when:
        _die(f"{where}: when must be an object with at least one key")
    unknown = set(when) - {"visible", "notVisible", "true", "minApi"}
    if unknown:
        _die(f"{where}: unknown when key(s) {sorted(unknown)}")
    out: dict[str, Any] = {}
    for key in ("visible", "notVisible"):
        if key in when:
            out[key] = selector_from_flow(when[key], f"{where}.{key}")
    if "true" in when:
        if not isinstance(when["true"], str) or not when["true"].strip():
            _die(f"{where}.true must be a non-empty expression")
        out["true"] = when["true"]
    if "minApi" in when:
        n = when["minApi"]
        if isinstance(n, bool) or not isinstance(n, int) or n < 1:
            _die(f"{where}.minApi must be a positive integer")
        out["minApi"] = n
    return out


def _require_str(body: dict, key: str, where: str, *, allow_empty: bool = False) -> None:
    value = body.get(key)
    if not isinstance(value, str) or (not allow_empty and not value):
        got = "nothing" if value is None else repr(value)
        _die(f"{where}: {key} must be a non-empty string, got {got}")


def _require_int(body: dict, key: str, where: str, *, minimum: int = 0) -> None:
    value = body.get(key)
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        _die(f"{where}: {key} must be an integer >= {minimum}")


def _require_selector(body: dict, where: str) -> None:
    if not any(k in body for k in SELECTOR_KEYS):
        _die(f"{where}: needs at least one selector key ({', '.join(sorted(SELECTOR_KEYS))})")


def _validate_selector_command(allowed: frozenset) -> Any:
    def check(body: dict, step: dict, where: str) -> None:
        _require_selector(body, where)
        unknown = set(body) - allowed
        if unknown:
            _die(f"{where}: unknown key(s) {sorted(unknown)}")
    return check


def _v_launch_app(body: dict, step: dict, where: str) -> None:
    _require_str(body, "package", where)
    if not isinstance(body.get("clearState", False), bool):
        _die(f"{where}: clearState must be a boolean")
    _reject(body, {"package", "clearState"} | MODIFIER_KEYS, where)


def _v_stop_app(body: dict, step: dict, where: str) -> None:
    _require_str(body, "package", where)
    _reject(body, {"package"} | MODIFIER_KEYS, where)


def _v_open_link(body: dict, step: dict, where: str) -> None:
    _require_str(body, "url", where)
    if body.get("package") is not None:
        _require_str(body, "package", where)
    _reject(body, {"url", "package"} | MODIFIER_KEYS, where)


def _v_input_text(body: dict, step: dict, where: str) -> None:
    if "into" not in body:
        _die(f"{where}: inputText needs an `into` selector (the broker acts on explicit targets)")
    selector_from_flow(body["into"], f"{where}: into")
    _require_str(body, "text", where, allow_empty=True)
    if not isinstance(body.get("secret", False), bool):
        _die(f"{where}: secret must be a boolean")
    _reject(body, {"into", "text", "secret"} | MODIFIER_KEYS, where)


def _v_erase_text(body: dict, step: dict, where: str) -> None:
    if "into" not in body:
        _die(f"{where}: eraseText needs an `into` selector")
    selector_from_flow(body["into"], f"{where}: into")
    _reject(body, {"into"} | MODIFIER_KEYS, where)


def _v_press_key(body: dict, step: dict, where: str) -> None:
    _require_str(body, "key", where)
    if body["key"] not in PRESS_KEYS:
        _die(f"{where}: key must be one of {sorted(PRESS_KEYS)}")
    _reject(body, {"key"} | MODIFIER_KEYS, where)


def _v_scroll(body: dict, step: dict, where: str) -> None:
    if body.get("direction", "down") not in DIRECTIONS:
        _die(f"{where}: direction must be one of {sorted(DIRECTIONS)}")
    _reject(body, {"direction"} | MODIFIER_KEYS, where)


def _v_swipe(body: dict, step: dict, where: str) -> None:
    for key in ("x1", "y1", "x2", "y2"):
        _require_int(body, key, where)
    if body.get("duration") is not None:
        _require_int(body, "duration", where, minimum=0)
    _reject(body, {"x1", "y1", "x2", "y2", "duration"} | MODIFIER_KEYS, where)


def _v_wait_until(body: dict, step: dict, where: str) -> None:
    if ("visible" in body) == ("notVisible" in body):
        _die(f"{where}: waitUntil needs exactly one of visible / notVisible")
    for key in ("visible", "notVisible"):
        if key in body:
            selector_from_flow(body[key], f"{where}: {key}")
    _reject(body, {"visible", "notVisible", "timeout"} | MODIFIER_KEYS, where)


def _v_wait_animation(body: dict, step: dict, where: str) -> None:
    _reject(body, {"timeout"} | MODIFIER_KEYS, where)


def _v_copy_text(body: dict, step: dict, where: str) -> None:
    _require_selector(body, where)
    _require_str(body, "into", where)
    _reject(body, SELECTOR_KEYS | {"into"} | MODIFIER_KEYS, where)


def _v_set_clipboard(body: dict, step: dict, where: str) -> None:
    _require_str(body, "text", where, allow_empty=True)
    if not isinstance(body.get("secret", False), bool):
        _die(f"{where}: secret must be a boolean")
    _reject(body, {"text", "secret"} | MODIFIER_KEYS, where)


def _v_take_screenshot(body: dict, step: dict, where: str) -> None:
    if body.get("into") is not None:
        _require_str(body, "into", where)
    _reject(body, {"into"} | MODIFIER_KEYS, where)


def _v_notify(body: dict, step: dict, where: str) -> None:
    _require_str(body, "title", where)
    _require_str(body, "text", where, allow_empty=True)
    _reject(body, {"title", "text"} | MODIFIER_KEYS, where)


def _v_ask(body: dict, step: dict, where: str) -> None:
    _require_str(body, "title", where)
    _require_str(body, "message", where)
    kind = body.get("kind", "confirm")
    if kind not in ASK_KINDS:
        _die(f"{where}: kind must be one of {sorted(ASK_KINDS)}")
    if kind == "choice":
        choices = body.get("choices")
        if not isinstance(choices, list) or not choices or not all(
                isinstance(c, str) and c for c in choices):
            _die(f"{where}: kind 'choice' needs a non-empty choices list of strings")
    elif "choices" in body:
        _die(f"{where}: choices is only valid with kind 'choice'")
    if kind in ("text", "choice") and "into" not in body:
        _die(f"{where}: kind '{kind}' needs `into` (the variable that receives the answer)")
    if body.get("into") is not None:
        _require_str(body, "into", where)
    _reject(body, {"title", "message", "kind", "choices", "into"} | MODIFIER_KEYS, where)


def _v_log(body: dict, step: dict, where: str) -> None:
    _require_str(body, "message", where)
    if body.get("level", "info") not in LOG_LEVELS:
        _die(f"{where}: level must be one of {sorted(LOG_LEVELS)}")
    _reject(body, {"message", "level"} | MODIFIER_KEYS, where)


def _v_set_result(body: dict, step: dict, where: str) -> None:
    _require_str(body, "code", where)
    if body.get("data") is not None and not isinstance(body["data"], dict):
        _die(f"{where}: data must be an object")
    _reject(body, {"code", "data"} | MODIFIER_KEYS, where)


def _v_next_run(body: dict, step: dict, where: str) -> None:
    _require_int(body, "afterMinutes", where, minimum=1)
    _reject(body, {"afterMinutes"} | MODIFIER_KEYS, where)


def _v_define_variables(body: dict, step: dict, where: str) -> None:
    # The body IS the variable map; the modifier names are reserved because the step parser
    # reads them before this validator sees the body.
    _check_env_map(body, f"{where}: defineVariables")
    reserved = sorted(set(body) & MODIFIER_KEYS)
    if reserved:
        _die(f"{where}: variable name(s) {reserved} are reserved modifiers")


def _v_run_flow(body: dict, step: dict, where: str) -> None:
    _require_str(body, "file", where)
    if body.get("env") is not None:
        _check_env_map(body["env"], f"{where}: runFlow env")
    _reject(body, {"file", "env"} | MODIFIER_KEYS, where)


def _v_repeat(body: dict, step: dict, where: str) -> None:
    if ("times" in body) == ("while" in body):
        _die(f"{where}: repeat needs exactly one of times / while")
    if "times" in body:
        _require_int(body, "times", where, minimum=1)
        step["times"] = body["times"]
    else:
        if not isinstance(body["while"], str) or not body["while"].strip():
            _die(f"{where}: while must be a non-empty expression")
        step["while"] = body["while"]
    if not isinstance(body.get("steps"), list) or not body["steps"]:
        _die(f"{where}: repeat needs a non-empty steps list")
    step["steps"] = _parse_steps(body["steps"], f"{where}: repeat steps")
    _reject(body, {"times", "while", "steps"} | MODIFIER_KEYS, where)


def _v_retry(body: dict, step: dict, where: str) -> None:
    _require_int(body, "times", where, minimum=0)
    step["times"] = body["times"]
    if body.get("backoff_ms") is not None:
        _require_int(body, "backoff_ms", where, minimum=0)
        step["backoff_ms"] = body["backoff_ms"]
    if not isinstance(body.get("steps"), list) or not body["steps"]:
        _die(f"{where}: retry needs a non-empty steps list")
    step["steps"] = _parse_steps(body["steps"], f"{where}: retry steps")
    _reject(body, {"times", "backoff_ms", "steps"} | MODIFIER_KEYS, where)


def _reject(body: dict, allowed: Any, where: str) -> None:
    unknown = set(body) - set(allowed)
    if unknown:
        _die(f"{where}: unknown key(s) {sorted(unknown)}")


