def _x_run_flow(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    name = _arg_str(step, "file", scope, label)
    doc = ex.subflows.get(name)
    if doc is None:
        raise StepFailure("INVALID_ARGS", f"subflow '{name}' is not registered", label=label)
    if state["depth"] + 1 > MAX_FLOW_DEPTH:
        raise StepFailure("INVALID_ARGS", f"flow nesting deeper than {MAX_FLOW_DEPTH}", label=label)
    child = parse_flow(doc)
    overlay = {key: resolve_value(value, scope)
               for key, value in (step["body"].get("env") or {}).items()}
    child_scope = scope.child({})
    child_scope.env.update(dict(child.get("env") or {}))
    child_scope.env.update(overlay)  # the explicit runFlow env wins over the child's static env
    state["depth"] += 1
    try:
        _run_steps(child.get("onFlowStart") or [], child_scope, ex, state)
        _run_steps(child["steps"], child_scope, ex, state)
        _run_steps(child.get("onFlowComplete") or [], child_scope, ex, state)
    finally:
        state["depth"] -= 1


def _x_repeat(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    steps = step["steps"]
    if "times" in step:
        for _ in range(step["times"]):
            ex.check()
            for inner in steps:
                _run_step(inner, scope, ex, state)
        return
    iterations = 0
    while True:
        value = _expr_value(step["while"], scope, label)
        if value is False:
            return
        if value is not True:  # a non-boolean condition is an authoring bug: fail closed
            raise StepFailure("INVALID_ARGS",
                              f"while must evaluate to true/false, got {value!r}", label=label)
        iterations += 1
        if iterations > MAX_WHILE_ITERATIONS:
            raise StepFailure("INVALID_ARGS", f"while exceeded {MAX_WHILE_ITERATIONS} iterations",
                              label=label)
        ex.check()
        for inner in steps:
            _run_step(inner, scope, ex, state)


def _x_retry(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    steps = step["steps"]
    times = step["times"]
    backoff_ms = step.get("backoff_ms", RETRY_BACKOFF_MS_DEFAULT)
    attempt = 0
    while True:
        ex.check()
        try:
            for inner in steps:
                _run_step(inner, scope, ex, state)
            return
        except StepFailure as exc:
            if not exc.retryable or attempt >= times:
                raise
            ex.sleep(backoff_ms / 1000.0)
            attempt += 1


