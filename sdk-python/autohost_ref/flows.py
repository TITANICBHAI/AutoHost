_TEMPLATE_RE = _re.compile(r"\$\{([^{}]+)\}")


class Scope:
    """Variable scope: config, profile, env (mutable), run info, secrets.

    Bare names resolve env -> config -> profile. Namespaced paths (config.x.y, profile.x,
    env.X, run.attempt) walk nested dicts. Secrets resolve only through lookup() with
    allow_secrets=True and only in action positions; everywhere else ${secret.NAME} stays
    literal (fail closed).
    """

    def __init__(self, config: dict, profile: dict, env: dict, run: dict, secrets: dict) -> None:
        self.config = config
        self.profile = profile
        self.env = env
        self.run = run
        self.secrets = secrets

    def lookup(self, path: str, *, allow_secrets: bool = False) -> tuple[bool, Any]:
        path = path.strip()
        if path.startswith("secret."):
            name = path[len("secret."):]
            if not allow_secrets:
                return False, None
            if name not in self.secrets:
                raise _SecretMissing(name)
            return True, self.secrets[name]
        namespace, dot, rest = path.partition(".")
        if dot and namespace in ("config", "profile", "env", "run"):
            table = {"config": self.config, "profile": self.profile,
                     "env": self.env, "run": self.run}[namespace]
            return _walk(table, rest)
        if not dot and namespace == "run" and path == "run":
            return True, self.run
        for table in (self.env, self.config, self.profile):
            if path in table:
                return True, table[path]
        return False, None

    def child(self, env_overlay: dict) -> "Scope":
        merged = dict(self.env)
        merged.update(env_overlay)
        return Scope(self.config, self.profile, merged, self.run, self.secrets)

    def redact(self, text: str) -> str:
        for value in self.secrets.values():
            if isinstance(value, str) and value:
                text = text.replace(value, "[REDACTED]")
        return text


def _walk(table: dict, path: str) -> tuple[bool, Any]:
    current: Any = table
    for part in path.split("."):
        if isinstance(current, dict) and part in current:
            current = current[part]
        else:
            return False, None
    return True, current


def resolve_value(value: Any, scope: Scope, *, allow_secrets: bool = False) -> Any:
    """Recursively resolves ${...} placeholders in strings; non-strings pass through."""
    if isinstance(value, str):
        return _resolve_string(value, scope, allow_secrets)
    if isinstance(value, list):
        return [resolve_value(item, scope, allow_secrets=allow_secrets) for item in value]
    if isinstance(value, dict):
        return {key: resolve_value(item, scope, allow_secrets=allow_secrets)
                for key, item in value.items()}
    return value


def _resolve_string(text: str, scope: Scope, allow_secrets: bool) -> Any:
    matches = list(_TEMPLATE_RE.finditer(text))
    if not matches:
        return text
    if len(matches) == 1 and matches[0].span() == (0, len(text)):
        found, value = scope.lookup(matches[0].group(1).strip(), allow_secrets=allow_secrets)
        return value if found else text
    def sub(match: _re.Match) -> str:
        found, value = scope.lookup(match.group(1).strip(), allow_secrets=allow_secrets)
        return _interpolate(value) if found else match.group(0)
    return _TEMPLATE_RE.sub(sub, text)


def _interpolate(value: Any) -> str:
    if value is None:
        return ""
    if value is True:
        return "true"
    if value is False:
        return "false"
    return str(value)


