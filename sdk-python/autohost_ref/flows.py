def _x_copy_text_from(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    wire = _selector_wire(step, scope, label)
    nodes = _find(ex, wire, 2, label)
    if not nodes:
        raise StepFailure("NOT_FOUND", "no element matches the selector", selector=wire, label=label)
    if len(nodes) > 1:
        raise StepFailure("INVALID_ARGS", f"selector matched {len(nodes)} nodes; copyTextFrom "
                                          f"needs exactly one", selector=wire, label=label)
    node = nodes[0]
    text = node.get("text")
    if text is None:
        text = node.get("desc")
    if text is None:
        raise StepFailure("NOT_FOUND", "node carries no text", selector=wire, label=label)
    scope.env[step["body"]["into"]] = text


