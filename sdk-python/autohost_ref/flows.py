def _x_launch_app(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    package = _arg_str(step, "package", scope, label)
    if _arg_bool(step, "clearState", label):
        _call(ex, "device.app", "stop", {"package": package}, label)
    _call(ex, "device.app", "launch", {"package": package}, label)


def _x_stop_app(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    package = _arg_str(step, "package", scope, label)
    _call(ex, "device.app", "stop", {"package": package}, label)


def _x_open_link(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    url = _arg_str(step, "url", scope, label)
    args: dict[str, Any] = {"uri": url}
    if "package" in step["body"]:
        args["package"] = _arg_str(step, "package", scope, label)
    _call(ex, "device.app", "launch", args, label)


def _x_tap_on(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    wire = _selector_wire(step, scope, label)
    if _arg_bool(step, "waitToSettle", label):
        _call(ex, "device.ui", "wait_for_settle", {}, label)
    args: dict[str, Any] = {"target": {"selector": wire}, "timeout_ms": _timeout_ms(step)}
    if _arg_bool(step, "retryTapIfNoChange", label):
        args["retry_if_no_change"] = True
    out = _call(ex, "device.ui", "click", args, label, selector=wire)
    if out.get("verified") is not True:
        raise StepFailure("TIMEOUT", "tap could not be verified", retryable=True, selector=wire,
                          label=label)


