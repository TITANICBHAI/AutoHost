# Commands whose body IS a selector plus modifiers (the executor splits the two apart).
SELECTOR_COMMANDS = frozenset({"tapOn", "longPressOn", "waitFor", "assertVisible",
                               "assertNotVisible", "scrollUntilVisible"})
# ---------------------------------------------------------------------------
# selectors: flow form -> broker wire form (schemas/broker.schema.json#/$defs/Selector)
# ---------------------------------------------------------------------------

def selector_from_flow(raw: Any, where: str = "selector") -> dict:
    """Normalises a flow selector into the broker wire form. Raises FlowError on garbage."""
    if not isinstance(raw, dict) or not raw:
        _die(f"{where}: selector must be a non-empty object")
    unknown = set(raw) - SELECTOR_KEYS
    if unknown:
        _die(f"{where}: unknown selector key(s) {sorted(unknown)}")
    base: dict[str, Any] = {}
    for key in LABEL_KEYS:
        if key in raw:
            base[key] = _match_spec(raw[key], key, where)
    for key in STATE_KEYS:
        if key in raw:
            value = raw[key]
            if not isinstance(value, bool):
                _die(f"{where}: {key} must be a boolean")
            base.setdefault("state", {})[key] = value
    if "bounds" in raw:
        bounds = raw["bounds"]
        if not isinstance(bounds, dict) or not bounds:
            _die(f"{where}: bounds must be an object with at least one side")
        unknown = set(bounds) - {"left", "top", "right", "bottom"}
        if unknown:
            _die(f"{where}: unknown bounds key(s) {sorted(unknown)}")
        for key, value in bounds.items():
            if isinstance(value, bool) or not isinstance(value, int):
                _die(f"{where}: bounds.{key} must be an integer")
        base["bounds"] = {k: bounds[k] for k in ("left", "top", "right", "bottom") if k in bounds}
    for key in RELATION_KINDS:
        if key in raw:
            base[key] = selector_from_flow(raw[key], f"{where}: {key}")
    if "containsDescendants" in raw:
        nested = raw["containsDescendants"]
        if not isinstance(nested, list) or not nested:
            _die(f"{where}: containsDescendants must be a non-empty list of selectors")
        base["containsDescendants"] = [
            selector_from_flow(item, f"{where}: containsDescendants[{i}]") for i, item in enumerate(nested)
        ]

    index = raw.get("index")
    if index is not None:
        if isinstance(index, bool) or not isinstance(index, int) or index < 0:
            _die(f"{where}: index must be a non-negative integer")
        # Fold every other criterion into a single index-relation term: the node must be the
        # index-th match of the rest (document order), mirroring the Kotlin SelectorEngine.
        return {"op": "and", "terms": [{"relation": {"kind": "index", "n": index,
                                                     "selector": _wire_from_parts(base)}}]}
    return _wire_from_parts(base)


def _match_spec(value: Any, key: str, where: str) -> dict:
    """text/id/desc/class/package: string | list of strings | {value, mode} -> broker Match."""
    if isinstance(value, str):
        if not value:
            _die(f"{where}: {key} must not be empty")
        return {"labels": [value], "mode": "eq", "case_sensitive": False}
    if isinstance(value, list):
        if not value or not all(isinstance(x, str) and x for x in value):
            _die(f"{where}: {key} must be a non-empty string or list of non-empty strings")
        return {"labels": list(value), "mode": "eq", "case_sensitive": False}
    if isinstance(value, dict):
        unknown = set(value) - {"value", "mode"}
        if unknown or not isinstance(value.get("value"), str) or not value["value"]:
            _die(f"{where}: {key} object form needs a non-empty `value` (and optional `mode`)")
        mode = value.get("mode", "eq")
        if mode not in MATCH_MODES:
            _die(f"{where}: {key} mode must be one of {list(MATCH_MODES)}")
        return {"labels": [value["value"]], "mode": mode, "case_sensitive": False}
    _die(f"{where}: {key} must be a string, a list of strings or an object")


def _wire_from_parts(base: dict) -> dict:
    terms: list[dict] = []
    for key in LABEL_KEYS:
        if key in base:
            wire_key = "pkg" if key == "package" else key
            terms.append({wire_key: base[key]})
    if "state" in base:
        terms.append({"state": base["state"]})
    if "bounds" in base:
        terms.append({"bounds": base["bounds"]})
    for key, kind in RELATION_KINDS.items():
        if key in base:
            terms.append({"relation": {"kind": kind, "selector": base[key]}})
    for nested in base.get("containsDescendants", ()):
        terms.append({"relation": {"kind": "contains_descendants", "selector": nested}})
    return {"op": "and", "terms": terms}


