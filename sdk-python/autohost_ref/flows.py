class Exec:
    """Host callback surface for the interpreter (duck-typed; the Kotlin side mirrors it).

    - broker: .call(capability, method, args) -> dict; raises BrokerError on failure.
    - emit(event): receives interpreter events (no `ts`; the host stamps time).
    - check(): raises Cancelled when the run was cancelled (called between steps).
    - sleep(seconds): cancellable sleep (retry backoff).
    - clock(): now in epoch ms (host-stamped; the interpreter itself does not read time).
    - api_level: for when.minApi (the host reads Build.VERSION via ApiGate).
    - subflows: {"name": flow_document} for runFlow (no filesystem in the reference).
    - viewport: (width, height) for scroll; default 1080x2400.
    """

    def __init__(self, broker: Any, *, emit: Any = None, check: Any = None, sleep: Any = None,
                 clock: Any = None, api_level: int = 29, subflows: dict | None = None,
                 viewport: tuple[int, int] = DEFAULT_VIEWPORT) -> None:
        self.broker = broker
        self.emit = emit or (lambda event: None)
        self.check = check or (lambda: None)
        self.sleep = sleep or (lambda seconds: None)
        self.clock = clock or (lambda: 0)
        self.api_level = int(api_level)
        self.subflows = dict(subflows or {})
        self.viewport = (int(viewport[0]), int(viewport[1]))


def run_flow(doc: dict, ex: Exec, *, config: dict | None = None, profile: dict | None = None,
             env: dict | None = None, secrets: dict | None = None,
             run: dict | None = None) -> dict:
    """Parses and runs a flow document against [ex]. Returns the run outcome (module docstring)."""
    flow = parse_flow(doc)
    base_env = dict(flow.get("env") or {})
    base_env.update(env or {})
    scope = Scope(dict(config or {}), dict(profile or {}), base_env,
                  dict(run or {"attempt": 1}), dict(secrets or {}))
    state: dict[str, Any] = {"result": {"code": "OK", "data": {}}, "next_run": None,
                             "step_no": 0, "depth": 0}
    try:
        ex.check()
        _run_steps(flow.get("onFlowStart") or [], scope, ex, state)
        _run_steps(flow["steps"], scope, ex, state)
        _run_steps(flow.get("onFlowComplete") or [], scope, ex, state)
        outcome: dict[str, Any] = {"status": "SUCCEEDED", "result": dict(state["result"])}
    except WaitUser as exc:
        outcome = {"status": "WAITING_USER", "reason": "NEEDS_INPUT", "message": str(exc)}
    except Cancelled:
        outcome = {"status": "CANCELLED", "reason": "USER_CANCELLED"}
    except StepFailure as exc:
        outcome = {"status": "FAILED", "reason": exc.code, "message": exc.message}
    if state["next_run"] is not None:
        outcome["next_run"] = dict(state["next_run"])
    return outcome


def _run_steps(steps: list[dict], scope: Scope, ex: Exec, state: dict) -> None:
    for step in steps:
        ex.check()
        _run_step(step, scope, ex, state)


def _run_step(step: dict, scope: Scope, ex: Exec, state: dict) -> None:
    command = step["command"]
    label_hint = step.get("label") or command
    try:
        if step.get("when") is not None and not _when_holds(step["when"], scope, ex, label_hint):
            return
        state["step_no"] += 1
        label = step.get("label") or f"{command}#{state['step_no']}"
        _EXECUTORS[command](step, scope, ex, state, label)
    except StepFailure as exc:
        if exc.label is None:
            exc.label = label_hint
        _emit_evidence(ex, scope, label_hint, command, exc)
        if step["optional"]:
            ex.emit({"type": "log", "level": "warn",
                     "message": scope.redact(
                         f"step '{label_hint}' failed and was skipped: {exc.code} ({exc.message})")})
            return
        raise


def _when_holds(when: dict, scope: Scope, ex: Exec, label: str) -> bool:
    try:
        if "visible" in when and not _find(ex, _resolve_selector_labels(when["visible"], scope), 1):
            return False
        if "notVisible" in when and _find(ex, _resolve_selector_labels(when["notVisible"], scope), 1):
            return False
        if "true" in when:
            value = eval_expr(when["true"], scope)
            if value is False:
                return False
            if value is not True:  # a non-boolean condition is an authoring bug: fail closed
                raise StepFailure("INVALID_ARGS",
                                  f"when.true must evaluate to true/false, got {value!r}", label=label)
        if "minApi" in when and ex.api_level < when["minApi"]:
            return False
    except _SecretMissing as exc:  # unreachable (expressions refuse secrets); kept for symmetry
        raise StepFailure("NOT_FOUND", f"secret '{exc.name}' is not declared for this profile",
                          label=label) from None
    except ExprError as exc:
        raise StepFailure("INVALID_ARGS", f"when expression failed: {exc}", label=label) from None
    return True


def _emit_evidence(ex: Exec, scope: Scope, label: str, command: str, exc: StepFailure) -> None:
    ex.emit({"type": "evidence", "data": {
        "step": label, "command": command, "code": exc.code, "retryable": exc.retryable,
        "message": scope.redact(exc.message), "selector": exc.selector,
    }})


def _call(ex: Exec, capability: str, method: str, args: dict, label: str,
          selector: dict | None = None) -> dict:
    """One broker call, converting BrokerError into the typed StepFailure."""
    try:
        return ex.broker.call(capability, method, args)
    except BrokerError as exc:
        raise StepFailure(exc.code, exc.message, retryable=exc.retryable, selector=selector,
                          label=label) from None


def _find(ex: Exec, wire: dict, limit: int, label: str = "when") -> list[dict]:
    out = _call(ex, "device.ui", "find", {"selector": wire, "limit": limit}, label, selector=wire)
    return list(out.get("nodes") or [])


def _timeout_ms(step: dict, default: float = DEFAULT_TIMEOUT_S) -> int:
    seconds = step.get("timeout_s")
    if seconds is None:
        seconds = default
    return int(round(seconds * 1000))


def _expr_value(expr: str, scope: Scope, label: str) -> Any:
    try:
        return eval_expr(expr, scope)
    except ExprError as exc:
        raise StepFailure("INVALID_ARGS", f"expression failed: {exc}", label=label) from None


def _arg_str(step: dict, key: str, scope: Scope, label: str, *, required: bool = True,
             default: str | None = None, allow_empty: bool = False,
             allow_secrets: bool = False) -> str:
    body = step["body"]
    if key not in body:
        if required:
            raise StepFailure("INVALID_ARGS", f"{label}: missing '{key}'", label=label)
        return default  # type: ignore[return-value]
    value = body[key]
    if not isinstance(value, str):
        raise StepFailure("INVALID_ARGS", f"{label}: {key} must be a string", label=label)
    resolved = _resolve_string(value, scope, allow_secrets)
    if not isinstance(resolved, str):
        raise StepFailure("INVALID_ARGS", f"{label}: {key} resolved to a non-string", label=label)
    if not allow_empty and not resolved:
        raise StepFailure("INVALID_ARGS", f"{label}: {key} must not be empty", label=label)
    return resolved


def _arg_bool(step: dict, key: str, label: str, default: bool = False) -> bool:
    value = step["body"].get(key, default)
    if not isinstance(value, bool):
        raise StepFailure("INVALID_ARGS", f"{label}: {key} must be a boolean", label=label)
    return value


def _secret_resolved(text: str, scope: Scope, label: str, allow_secrets: bool) -> str:
    try:
        resolved = _resolve_string(text, scope, allow_secrets)
    except _SecretMissing as exc:
        raise StepFailure("NOT_FOUND", f"secret '{exc.name}' is not declared for this profile",
                          label=label) from None
    if not isinstance(resolved, str):
        raise StepFailure("INVALID_ARGS", f"{label}: text resolved to a non-string", label=label)
    return resolved


def _selector_wire(step: dict, scope: Scope, label: str) -> dict:
    """Builds the wire selector from the body's selector keys and resolves its labels."""
    body = step["body"]
    raw: dict[str, Any] = {}
    for key in SELECTOR_KEYS:
        if key in body:
            raw[key] = body[key]
    wire = selector_from_flow(raw, label)
    return _resolve_selector_labels(wire, scope)


def _resolve_selector_labels(wire: dict, scope: Scope) -> dict:
    """Resolves ${...} inside match labels; unresolved placeholders stay literal (fail closed)."""
    out: dict[str, Any] = {}
    for key, value in wire.items():
        if key == "terms":
            terms = []
            for term in value:
                (term_key, spec), = term.items()
                if term_key in ("text", "desc", "id", "class", "pkg"):
                    spec = dict(spec)
                    spec["labels"] = [
                        _resolve_string(label, scope, False) if isinstance(label, str) else label
                        for label in spec["labels"]
                    ]
                    if not all(isinstance(x, str) for x in spec["labels"]):
                        raise StepFailure("INVALID_ARGS", "selector label resolved to a non-string")
                    terms.append({term_key: spec})
                elif term_key == "relation":
                    relation = dict(spec)
                    relation["selector"] = _resolve_selector_labels(relation["selector"], scope)
                    terms.append({"relation": relation})
                elif term_key == "sel":
                    terms.append({"sel": _resolve_selector_labels(spec, scope)})
                else:
                    terms.append(term)
            out["terms"] = terms
        elif key == "within":
            out["within"] = _resolve_selector_labels(value, scope)
        else:
            out[key] = value
    return out


