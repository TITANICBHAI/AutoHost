_EXPR_TOKEN = _re.compile(r"""
    (?P<ws>\s+)
  | (?P<num>\d+(?:\.\d+)?)
  | (?P<str>'[^']*'|"[^"]*")
  | (?P<op>==|!=|<=|>=|&&|\|\||[<>!+\-()])
  | (?P<name>[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)
""", _re.X)

_EXPR_OPS = {"==", "!=", "<", "<=", ">", ">=", "&&", "||", "+", "-", "!", "(", ")"}


def _tokenize(expr: str) -> list[tuple[str, Any]]:
    tokens: list[tuple[str, Any]] = []
    pos = 0
    while pos < len(expr):
        match = _EXPR_TOKEN.match(expr, pos)
        if match is None:
            raise ExprError(f"unexpected character {expr[pos]!r} at {pos}")
        pos = match.end()
        if match.lastgroup == "ws":
            continue
        if match.lastgroup == "num":
            text = match.group("num")
            tokens.append(("num", float(text) if "." in text else int(text)))
        elif match.lastgroup == "str":
            tokens.append(("str", match.group("str")[1:-1]))
        elif match.lastgroup == "op":
            op = match.group("op")
            if op not in _EXPR_OPS:
                raise ExprError(f"unknown operator {op!r}")
            tokens.append(("op", op))
        else:
            tokens.append(("name", match.group("name")))
    tokens.append(("end", None))
    return tokens


def eval_expr(expr: str, scope: Scope) -> Any:
    """Evaluates a side-effect-free expression. Raises ExprError on syntax/evaluation problems."""
    parser = _ExprParser(_tokenize(expr), scope)
    value = parser.parse_or()
    if parser.peek()[0] != "end":
        raise ExprError(f"unexpected trailing input in {expr!r}")
    return value


class _ExprParser:
    def __init__(self, tokens: list[tuple[str, Any]], scope: Scope) -> None:
        self.tokens = tokens
        self.pos = 0
        self.scope = scope

    def peek(self) -> tuple[str, Any]:
        return self.tokens[self.pos]

    def take_op(self, *ops: str) -> str | None:
        kind, value = self.peek()
        if kind == "op" and value in ops:
            self.pos += 1
            return value
        return None

    def parse_or(self) -> Any:
        value = self.parse_and()
        while self.take_op("||"):
            right = self.parse_and()
            if not isinstance(value, bool) or not isinstance(right, bool):
                raise ExprError("&& and || need booleans on both sides")
            value = value or right
        return value

    def parse_and(self) -> Any:
        value = self.parse_not()
        while self.take_op("&&"):
            right = self.parse_not()
            if not isinstance(value, bool) or not isinstance(right, bool):
                raise ExprError("&& and || need booleans on both sides")
            value = value and right
        return value

    def parse_not(self) -> Any:
        if self.take_op("!"):
            value = self.parse_not()
            if not isinstance(value, bool):
                raise ExprError("! needs a boolean")
            return not value
        return self.parse_comparison()

    def parse_comparison(self) -> Any:
        left = self.parse_additive()
        op = self.take_op("==", "!=", "<", "<=", ">", ">=")
        if op is None:
            return left
        right = self.parse_additive()
        return _compare(op, left, right)

    def parse_additive(self) -> Any:
        value = self.parse_unary()
        while True:
            op = self.take_op("+", "-")
            if op is None:
                return value
            right = self.parse_unary()
            if op == "+":
                if _is_num(value) and _is_num(right):
                    value = value + right
                elif isinstance(value, str) and isinstance(right, str):
                    value = value + right
                else:
                    raise ExprError("+ needs two numbers or two strings")
            else:
                if _is_num(value) and _is_num(right):
                    value = value - right
                else:
                    raise ExprError("- needs two numbers")

    def parse_unary(self) -> Any:
        if self.take_op("-"):
            value = self.parse_unary()
            if not _is_num(value):
                raise ExprError("- needs a number")
            return -value
        return self.parse_atom()

    def parse_atom(self) -> Any:
        kind, value = self.peek()
        if kind == "op" and value == "(":
            self.pos += 1
            inner = self.parse_or()
            if self.take_op(")") is None:
                raise ExprError("missing closing parenthesis")
            return inner
        if kind in ("num", "str"):
            self.pos += 1
            return value
        if kind == "name":
            self.pos += 1
            if value == "true":
                return True
            if value == "false":
                return False
            return self._resolve_name(value)
        raise ExprError(f"expected a value, got {value!r}")

    def _resolve_name(self, name: str) -> Any:
        if name.startswith("secret."):
            raise ExprError("secrets cannot be used in expressions")
        namespace, dot, _rest = name.partition(".")
        if dot and namespace in ("config", "profile", "env", "run"):
            table = {"config": self.scope.config, "profile": self.scope.profile,
                     "env": self.scope.env, "run": self.scope.run}[namespace]
            found, value = _walk(table, _rest)
            if not found:
                raise ExprError(f"unknown variable '{name}'")
            return value
        for table in (self.scope.env, self.scope.config, self.scope.profile):
            if name in table:
                return table[name]
        raise ExprError(f"unknown variable '{name}'")


def _is_num(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _compare(op: str, left: Any, right: Any) -> bool:
    if op == "==":
        if isinstance(left, bool) != isinstance(right, bool):
            return False
        return left == right
    if op == "!=":
        return not _compare("==", left, right)
    if _is_num(left) and _is_num(right):
        pass
    elif isinstance(left, str) and isinstance(right, str):
        pass
    else:
        raise ExprError(f"ordering '{op}' needs two numbers or two strings")
    if op == "<":
        return left < right
    if op == "<=":
        return left <= right
    if op == ">":
        return left > right
    return left >= right


