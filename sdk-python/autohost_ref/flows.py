def _x_scroll(step: dict, scope: Scope, ex: Exec, state: dict, label: str) -> None:
    direction = step["body"].get("direction", "down")
    width, height = ex.viewport
    cx, cy = width // 2, height // 2
    edges = {"down": (cx, int(height * 0.7), cx, int(height * 0.3)),
             "up": (cx, int(height * 0.3), cx, int(height * 0.7)),
             "left": (int(width * 0.8), cy, int(width * 0.2), cy),
             "right": (int(width * 0.2), cy, int(width * 0.8), cy)}
    x1, y1, x2, y2 = edges[direction]
    _call(ex, "device.ui", "swipe",
          {"x1": x1, "y1": y1, "x2": x2, "y2": y2, "duration_ms": 300}, label)


